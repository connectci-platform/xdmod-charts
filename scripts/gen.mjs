// Generates src/generated/*.ts from rules/*.json. A missing rules file yields an empty value.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src", "generated");
mkdirSync(out, { recursive: true });

function load(name, empty) {
  const file = join(root, "rules", name);
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : empty;
}

const header = "// Generated by scripts/gen.mjs from rules/*.json. Do not edit.\n";

const statistics = load("statistics.json", {});
writeFileSync(
  join(out, "statistics.ts"),
  `${header}export type Statistic = { kind: "total" | "average"; unit: string; additive: boolean };\nexport const STATISTICS: Record<string, Statistic> = ${JSON.stringify(statistics, null, 2)};\n`,
);

const palette = load("palette.json", { light: [], dark: [] });
writeFileSync(
  join(out, "palette.ts"),
  `${header}export const PALETTE: { light: readonly string[]; dark: readonly string[] } = ${JSON.stringify(palette, null, 2)};\n`,
);
